local outputOverrides = {
    ab_ingmine_goldpearl_01 = 'ab_ingmine_goldpearl_g ',
    ingred_cursed_daedras_heart_01 = 'ingred_daedras_heart_g',
}

local function outputFor(records, id)
    local exact = records[id .. 'g']
    if exact then return exact end
    local stem = id:match('^(.-)_[%w]+$')
    return stem and records[stem .. '_g'] or nil
end

function rules.groundOutput(records, id)
    id = id:lower()
    if not rules.insoluble[id] and not rules.poorlySoluble[id] then return nil end
    local override = outputOverrides[id]
    if override then
        local result = records[override]
        if result then return result end
    end
    local normalized = id:gsub('_dae_cursed_', '_')
    local result = outputFor(records, normalized)
    if not result and normalized:sub(1, 5) == 't_ing' then
        local uncursed = normalized:gsub('dae(_[%w]+)$', '%1')
        if uncursed ~= normalized then result = outputFor(records, uncursed) end
    end
    return result
end

return rules
